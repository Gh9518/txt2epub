local B64CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local B64VAL = {}
do
    for i = 1, 64 do B64VAL[B64CHARS:sub(i, i):byte()] = i - 1 end
end

local function b64_decode(s)
    local out = {}
    local n = #s
    local i = 1
    local o = 0
    while i <= n do
        local c1 = B64VAL[s:byte(i)];   if not c1 then break end; i = i + 1
        local c2 = B64VAL[s:byte(i) or 0]; c2 = c2 or 0; i = i + 1
        local c3 = B64VAL[s:byte(i) or 0]; c3 = c3 or 0; i = i + 1
        local c4 = B64VAL[s:byte(i) or 0]; c4 = c4 or 0; i = i + 1
        o = o + 1; out[o] = string.char(c1 * 4 + math.floor(c2 / 16))
        if c3 ~= 0 or s:byte(i - 1) ~= 61 then
            o = o + 1; out[o] = string.char((c2 % 16) * 16 + math.floor(c3 / 4))
        end
        if c4 ~= 0 or s:byte(i) ~= 61 then
            o = o + 1; out[o] = string.char((c3 % 4) * 64 + c4)
        end
    end
    return table.concat(out)
end

local DATA = nil
local function get_data()
    if not DATA then DATA = b64_decode(DATA_B64) end
    return DATA
end

local NTRAIL = 94  -- 0xFE - 0xA1 + 1

local function cp_at(lead, trail)
    if lead < 0xA1 or lead > 0xF7 or trail < 0xA1 or trail > 0xFE then return 0 end
    local idx = ((lead - 0xA1) * NTRAIL + (trail - 0xA1)) * 2
    local d = get_data()
    return d:byte(idx + 1) + d:byte(idx + 2) * 256
end
-- 码点 -> UTF-8（纯算术，不用 utf8 库；真机 LuaJIT 无 utf8 库）
local function cp2utf8(u)
    if u < 0x80 then
        return string.char(u)
    elseif u < 0x800 then
        return string.char(0xC0 + math.floor(u / 64), 0x80 + (u % 64))
    elseif u < 0x10000 then
        return string.char(
            0xE0 + math.floor(u / 4096),
            0x80 + (math.floor(u / 64) % 64),
            0x80 + (u % 64))
    end
    return string.char(
        0xF0 + math.floor(u / 262144),
        0x80 + (math.floor(u / 4096) % 64),
        0x80 + (math.floor(u / 64) % 64),
        0x80 + (u % 64))
end

local REPL = "\239\191\189"  -- U+FFFD

-- 解码一段 GB2312 字节串为 UTF-8
function M.to_utf8(raw)
    if type(raw) ~= "string" then return nil end
    local out = {}
    local i, n = 1, #raw
    while i <= n do
        local b = raw:byte(i)
        if b < 0x80 then
            out[#out + 1] = string.char(b)
            i = i + 1
        elseif i < n then
            local b2 = raw:byte(i + 1)
            local cp = cp_at(b, b2)
            if cp ~= 0 then
                out[#out + 1] = cp2utf8(cp)
            else
                out[#out + 1] = REPL
            end
            i = i + 2
        else
            out[#out + 1] = REPL
            i = i + 1
        end
    end
    return table.concat(out)
end

-- 流式解码：按 64KB 块读取，块边界回退到完整双字节，逐块解码追加到 outfile。
-- 换行 0x0A / 回车 0x0D < 0x80，不会成为 GBK 双字节的低字节，故按字节扫描安全。
function M.decode_stream(inpath, outpath, chunk_size)
    local fin = io.open(inpath, "rb")
    if not fin then return nil, "无法打开输入文件" end
    local fout = io.open(outpath, "wb")
    if not fout then fin:close(); return nil, "无法打开输出文件" end
    chunk_size = chunk_size or 65536
    local carry = ""
    local total = 0
    while true do
        local chunk = fin:read(chunk_size)
        if not chunk or chunk == "" then break end
        local s = carry .. chunk
        carry = ""
        local n = #s
        if n > 0 then
            local last = s:byte(n)
            if last >= 0x81 and last <= 0xFE then
                carry = s:sub(n)
                s = s:sub(1, n - 1)
            end
        end
        if s ~= "" then
            local utf = M.to_utf8(s)
            fout:write(utf)
            total = total + #utf
        end
    end
    if carry ~= "" then
        fout:write(M.to_utf8(carry))
    end
    fout:close()
    fin:close()
    return true, total
end

return M
